//! Generates Rust code from the vendored `fleet-telemetry` protobuf schema
//! (`proto/`, see `proto/README.md`).
//!
//! `protox` parses the `.proto` files in Rust. No `protoc` binary and no C
//! toolchain are needed (ADR 0001, "Wire format: protobuf" and "Crates").
//! The build writes two kinds of file to `OUT_DIR`:
//!
//! - `prost-build` writes the Rust types, one file for each protobuf
//!   package, for example `telemetry.vehicle_data.rs`.
//! - `schema_fields.rs` lists the field numbers of each message type. The
//!   decode uses the list to find fields that the vendored schema does not
//!   know (`src/decode/unknown_fields.rs`).
//!
//! The build also watches `migrations/` and `db/roles.sql`: `sqlx::migrate!`
//! and `include_str!` embed them, and a procedural macro cannot ask Cargo
//! to rebuild when a file of a directory changes.

use std::error::Error;
use std::fmt::Write as _;
use std::path::PathBuf;

use prost_types::field_descriptor_proto::Type;
use prost_types::{DescriptorProto, FileDescriptorSet};

/// The vendored files that the ingest process decodes. Upstream also has
/// `vehicle_metric.proto`. No record type of the server configuration
/// dispatches it, so it is not vendored (`proto/README.md`).
const PROTO_FILES: [&str; 4] = [
    "proto/vehicle_data.proto",
    "proto/vehicle_alert.proto",
    "proto/vehicle_error.proto",
    "proto/vehicle_connectivity.proto",
];

/// The top-level message of each record type, and the name of the Rust
/// constant that holds its index in `MESSAGES`.
const ROOTS: [(&str, &str); 4] = [
    (".telemetry.vehicle_data.Payload", "PAYLOAD"),
    (".telemetry.vehicle_alerts.VehicleAlerts", "VEHICLE_ALERTS"),
    (".telemetry.vehicle_error.VehicleErrors", "VEHICLE_ERRORS"),
    (
        ".telemetry.vehicle_connectivity.VehicleConnectivity",
        "VEHICLE_CONNECTIVITY",
    ),
];

fn main() -> Result<(), Box<dyn Error>> {
    for file in PROTO_FILES {
        println!("cargo:rerun-if-changed={file}");
    }
    println!("cargo:rerun-if-changed=../../migrations");
    println!("cargo:rerun-if-changed=../../db/roles.sql");
    // `google/protobuf/timestamp.proto` is built into protox.
    let descriptors = protox::compile(PROTO_FILES, ["proto"])?;
    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").ok_or("OUT_DIR is not set")?);
    std::fs::write(
        out_dir.join("schema_fields.rs"),
        schema_fields(&descriptors)?,
    )?;
    prost_build::Config::new()
        // `map<string, string>` becomes a `BTreeMap`, so that the order of
        // the error tags does not depend on a hash seed.
        .btree_map(["."])
        .compile_fds(descriptors)?;
    Ok(())
}

/// Writes the table of message types and field numbers as Rust code.
fn schema_fields(descriptors: &FileDescriptorSet) -> Result<String, Box<dyn Error>> {
    let mut messages = Vec::new();
    for file in &descriptors.file {
        let prefix = format!(".{}", file.package());
        for message in &file.message_type {
            collect(&prefix, message, &mut messages);
        }
    }
    let index = |name: &str| {
        messages
            .iter()
            .position(|(full_name, _)| full_name == name)
            .ok_or_else(|| format!("message type {name} is not in the schema"))
    };

    let mut code = String::from(
        "// @generated by build.rs from the vendored .proto files.\n\
         // Each entry is one message type. A field is its number and, for a\n\
         // field of a message type, the index of that type.\n",
    );
    writeln!(
        code,
        "pub(super) static MESSAGES: [Message; {}] = [",
        messages.len()
    )?;
    for (name, message) in &messages {
        writeln!(code, "    // {name}")?;
        code.push_str("    Message { fields: &[");
        for field in &message.field {
            let child = if field.r#type() == Type::Message {
                format!("Some({})", index(field.type_name())?)
            } else {
                "None".to_owned()
            };
            write!(
                code,
                "Field {{ number: {}, message: {child} }}, ",
                field.number()
            )?;
        }
        code.push_str("] },\n");
    }
    code.push_str("];\n");
    for (name, constant) in ROOTS {
        writeln!(
            code,
            "pub(super) const {constant}: usize = {};",
            index(name)?
        )?;
    }
    Ok(code)
}

/// Adds a message type and its nested types, with their full names.
fn collect(prefix: &str, message: &DescriptorProto, messages: &mut Vec<(String, DescriptorProto)>) {
    let name = format!("{prefix}.{}", message.name());
    for nested in &message.nested_type {
        collect(&name, nested, messages);
    }
    messages.push((name, message.clone()));
}
